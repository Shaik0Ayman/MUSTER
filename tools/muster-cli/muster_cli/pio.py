"""PlatformIO project generation, build and upload. Fully deterministic: no
model touches this file's output.

One shared source tree, one environment per image. By default an image is one
board; in a shared-image project (images.py) all boards of a type that can read
a chip ID are ONE image whose node ID is derived at run time. Each image gets
its role, its capabilities, its CAN link and pins (from the board DB) and
bitmasks of resident task and module IDs as build flags. muster_gen.h registers only
resident tasks, so with -ffunction-sections/--gc-sections the linker drops
every task a board does not hold: a Nano never pays flash for the IMU filter
it will never run.
"""
import os
import re
import shutil
import subprocess
from pathlib import Path

from . import images as _images
from .codegen import generate_header, generate_plan_header

RUNTIME_HEADERS = ["muster.h", "muster_link_twai.h", "muster_link_mcp2515.h"]
CAP_BITS = {"fpu": 1, "wifi": 2, "ble": 4}           # MUSTER_CAP_* in muster.h
MCP2515_LIB = "autowp/autowp-mcp2515"
GEN_INCLUDE = '#include "muster_gen.h"   /* added by muster: typed glue for the tasks above */'
ANNOT_INCLUDE = '#include "muster_annotations.h"   /* added by muster: MUSTER_TASK(...) */'


class GenerationError(Exception):
    pass


def env_name(b):
    return b["id"].replace("-", "_")


def find_firmware_src():
    """The runtime headers: $MUSTER_FIRMWARE, else this repo's firmware/src."""
    candidates = []
    if os.environ.get("MUSTER_FIRMWARE"):
        candidates.append(Path(os.environ["MUSTER_FIRMWARE"]))
    candidates.append(Path(__file__).resolve().parents[3] / "firmware" / "src")
    for c in candidates:
        if (c / "muster.h").is_file():
            return c
    raise GenerationError("cannot find the runtime (firmware/src/muster.h); set "
                          "MUSTER_FIRMWARE to the directory that holds muster.h")


def find_pio():
    exe = shutil.which("pio") or shutil.which("platformio")
    if exe:
        return exe
    home = Path.home() / ".platformio" / "penv"
    for p in (home / "Scripts" / "pio.exe", home / "bin" / "pio"):
        if p.is_file():
            return str(p)
    raise GenerationError("PlatformIO not found: install it (pip install platformio) "
                          "or the VS Code extension")


def _pin_number(label):
    """'GPIO5' -> 5, 'D10' -> 10. Labels come from boards.yaml only."""
    m = re.fullmatch(r"(?:GPIO|D)(\d+)", str(label))
    if not m:
        raise GenerationError(f"pin label '{label}' in boards.yaml is not GPIOn or Dn")
    return int(m.group(1))


def _link_flags(b):
    can = b["spec"]["can"]
    if can["native"]:
        return ["-DMUSTER_GEN_LINK_TWAI",
                f"-DMUSTER_GEN_CAN_TX={_pin_number(can['pins']['tx'])}",
                f"-DMUSTER_GEN_CAN_RX={_pin_number(can['pins']['rx'])}"], []
    if can.get("module") == "mcp2515_tja1050":
        return ["-DMUSTER_GEN_LINK_MCP2515",
                f"-DMUSTER_GEN_MCP_CS={_pin_number(can['pins']['cs'])}"], [MCP2515_LIB]
    raise GenerationError(f"board '{b['id']}': no CAN link muster can generate for "
                          f"{can}")


def _sketch_with_include(source_text, analysis):
    """The sketch, with MUSTER_TASK defined first and the glue after the last task."""
    lines = source_text.splitlines()
    if not analysis["has_gen_include"]:
        at = analysis["insert_line"]
        lines = lines[:at] + ["", GEN_INCLUDE] + lines[at:]
    return "\n".join([ANNOT_INCLUDE] + lines) + "\n"


def _ini(plan, inventory, resident, task_ids, analysis=None, modmask=None):
    analysis, modmask = analysis or {}, modmask or {}
    modules = analysis.get("modules", [])
    counts = {m["module"]: m.get("count") for m in plan.get("modules", [])}
    ini = ["; GENERATED by muster - do not edit by hand. Re-run `muster plan`.", "",
           "[env]",
           "build_flags =",
           "    -ffunction-sections -fdata-sections",
           "    -Wl,--gc-sections", ""]
    for img in _images.images(inventory, plan["lead"]):
        b = img["boards"][0]
        spec, p = b["spec"], b["spec"]["pio"]
        is_lead = b["id"] == plan["lead"]
        rmask = 0
        mmask = 0
        for x in img["boards"]:
            rmask |= resident[x["id"]]
            mmask |= modmask.get(x["id"], 0)
        held = [n for n, i in task_ids.items() if rmask & (1 << i)]
        held += [m["name"] + "()" for i, m in enumerate(modules) if mmask & (1 << i)]
        link, libs = _link_flags(b)
        flags = [f"-DMUSTER_NODE_ID={img['node_id'] or 0}"]
        if img["shared"]:
            flags.append("-DMUSTER_ID_FROM_UID=1")
        flags += [f"-DMUSTER_LEAD={1 if is_lead else 0}",
                  f"-DMUSTER_RESIDENT_MASK={rmask:#x}ul",
                  f"-DMUSTER_GEN_CORES={spec['cores']}",
                  f"-DMUSTER_GEN_RAM_KB={spec['ram_kb']}",
                  f"-DMUSTER_GEN_CLOCK_MHZ={spec['clock_mhz']}",
                  f"-DMUSTER_GEN_FLAGS={sum(CAP_BITS[f] for f in spec['flags'])}"] + link
        if modules:
            flags.append(f"-DMUSTER_MODULE_MASK={mmask:#x}")
            if is_lead:                      # only the lead decides how many boards run a module
                flags += [f"-DMUSTER_MODULE_COUNT_{m['name'].upper()}={counts[m['name']] or m['count']}"
                          for m in modules if m["name"] in counts]
        if img["shared"]:
            ids = ", ".join(x["id"] for x in img["boards"])
            head = (f"; {b['type']}: {spec['name']}, ONE image for {ids} (node ID from the chip), "
                    f"holds {', '.join(held) or 'nothing'}")
        else:
            head = (f"; {b['id']}: {spec['name']}, node {img['node_id']}"
                    f"{', LEAD' if is_lead else ''}, holds {', '.join(held) or 'nothing'}")
        ini += [head,
                f"[env:{img['env']}]",
                f"platform = {p['platform']}",
                f"board = {p['board']}",
                f"framework = {p['framework']}",
                "monitor_speed = 115200",
                "build_flags =",
                "    ${env.build_flags}"] + [f"    {f}" for f in flags]
        if libs:
            ini += ["lib_deps ="] + [f"    {lib}" for lib in libs]
        if b.get("port") and not img["shared"]:      # a shared image has several ports
            ini += [f"upload_port = {b['port']}", f"monitor_port = {b['port']}"]
        ini.append("")
    return "\n".join(ini)


def generate_project(plan, analysis, inventory, source_path, out_dir):
    """Write the project. The caller must have validated the plan."""
    out = Path(out_dir)
    src, inc = out / "src", out / "include"
    src.mkdir(parents=True, exist_ok=True)
    inc.mkdir(parents=True, exist_ok=True)
    for stale in (src / "muster_registry_gen.cpp",):        # from muster-cli 0.1
        stale.unlink(missing_ok=True)

    task_ids = {t["name"]: i for i, t in enumerate(analysis["tasks"])}
    resident = {b["id"]: 0 for b in inventory}
    for a in plan["assignments"]:
        for bid in a["boards"]:
            resident[bid] |= 1 << task_ids[a["task"]]

    fw = find_firmware_src()
    for h in RUNTIME_HEADERS:
        shutil.copy(fw / h, inc / h)
    source = Path(source_path)
    for rel in analysis.get("local_headers", []):      # modules/tasks kept in their own headers
        (src / rel).parent.mkdir(parents=True, exist_ok=True)
        shutil.copy(source.resolve().parent / rel, src / rel)
    mod_ids = {m["name"]: i for i, m in enumerate(analysis.get("modules", []))}
    modmask = {b["id"]: 0 for b in inventory}
    for pm in plan.get("modules", []):
        for bid in pm["boards"]:
            modmask[bid] |= 1 << mod_ids[pm["module"]]
    sketch = src / (source.stem + ".cpp")
    sketch.write_text(_sketch_with_include(source.read_text(encoding="utf-8"), analysis),
                      encoding="utf-8")
    (inc / "muster_annotations.h").write_text(
        "#pragma once\n"
        "/* MUSTER_TASK(...) is read by the muster toolchain and expands to\n"
        "   nothing for the compiler. */\n"
        "#define MUSTER_TASK(...)\n"
        "/* MUSTER_MODULE(...) marks int8_t name(uint8_t event): a long-running unit the\n"
        "   lead assigns to boards. It is called with these events. START may return < 0\n"
        "   to decline (hardware missing); the lead then tries another board. */\n"
        "#define MUSTER_MODULE(...)\n"
        "#define MUSTER_MOD_START 0\n"
        "#define MUSTER_MOD_RUN 1\n"
        "#define MUSTER_MOD_STOP 2\n")
    (inc / "muster_plan.h").write_text(generate_plan_header(analysis))
    (inc / "muster_gen.h").write_text(generate_header(analysis))
    (src / "muster_runtime.cpp").write_text(
        "/* GENERATED by muster: the runtime's single implementation unit. */\n"
        "#include <Arduino.h>\n#define MUSTER_IMPLEMENTATION\n#include \"muster.h\"\n")
    ini = out / "platformio.ini"
    ini.write_text(_ini(plan, inventory, resident, task_ids, analysis, modmask))
    imgs = _images.images(inventory, plan["lead"])
    return {
        "platformio_ini": str(ini),
        "sketch": str(sketch),
        "envs": [img["env"] for img in imgs],
        "images": {img["env"]: [x["id"] for x in img["boards"]] for img in imgs},
        "resident": {bid: f"{m:#x}" for bid, m in resident.items()},
        "module_masks": {bid: f"{m:#x}" for bid, m in modmask.items()},
        "files": sorted(str(p.relative_to(out)).replace("\\", "/")
                        for p in out.rglob("*") if p.is_file() and ".pio" not in p.parts),
    }


def build(project_dir, envs=None, timeout=1800):
    """pio run (compile only) for the given envs, or all. Returns per-env results."""
    pio = find_pio()
    results = []
    for env in envs or [None]:
        cmd = [pio, "run", "-d", str(project_dir)] + (["-e", env] if env else [])
        r = subprocess.run(cmd, capture_output=True, text=True, timeout=timeout)
        log = (r.stdout or "") + (r.stderr or "")
        results.append({
            "env": env or "all",
            "ok": r.returncode == 0,
            "summary": [l for l in log.splitlines()
                        if re.search(r"SUCCESS|FAILED|RAM:|Flash:|error:", l)][-40:],
        })
    return results


def deploy(inventory, project_dir, lead, dry_run=True):
    """Build and upload every board, lead last so workers are listening first."""
    pio = find_pio() if not dry_run else "pio"
    order = sorted(inventory, key=lambda b: b["id"] == lead)
    steps = []
    for b in order:
        env = _images.env_for(b, inventory, lead)
        cmd = [pio, "run", "-d", str(project_dir), "-e", env, "-t", "upload"]
        if _images.is_shared(b, lead) and b.get("port"):     # one env, several boards
            cmd += ["--upload-port", b["port"]]
        step = {"board": b["id"], "command": " ".join(cmd), "ran": not dry_run}
        if not dry_run:
            r = subprocess.run(cmd, capture_output=True, text=True)
            step["ok"] = r.returncode == 0
            step["tail"] = ((r.stdout or "") + (r.stderr or "")).splitlines()[-15:]
            steps.append(step)
            if not step["ok"]:
                break                       # don't leave the bus half-flashed
        else:
            steps.append(step)
    return steps
