"""PlatformIO generation. Fully deterministic: no LLM touches this file's output.

One shared source tree, one environment per board. Each board gets its node
ID, its role, and a bitmask of resident task IDs as build flags. The
generated registry only references resident tasks, so with
-ffunction-sections/--gc-sections the linker drops every task a board does
not hold. A Nano never pays flash for the IMU filter it will never run.
"""
import shutil
import subprocess
from pathlib import Path


def _env_name(b):
    return b["id"].replace("-", "_")


def generate_project(plan, analysis, inventory, source_path, out_dir):
    out = Path(out_dir)
    (out / "src").mkdir(parents=True, exist_ok=True)
    (out / "include").mkdir(parents=True, exist_ok=True)
    shutil.copy(source_path, out / "src" / Path(source_path).name)

    task_ids = {t["name"]: i for i, t in enumerate(analysis["tasks"])}
    resident = {b["id"]: 0 for b in inventory}
    for a in plan["assignments"]:
        for bid in a["boards"]:
            resident[bid] |= 1 << task_ids[a["task"]]

    # ---- include/muster_annotations.h : makes the annotations compile ------
    (out / "include" / "muster_annotations.h").write_text(
        "#pragma once\n"
        "/* MUSTER_TASK(...) is read by the muster toolchain at build time and\n"
        "   expands to nothing for the compiler. */\n"
        "#define MUSTER_TASK(...)\n")

    # ---- include/muster_plan.h : task IDs, generated -----------------------
    lines = ["#pragma once", "/* GENERATED by muster - do not edit. */", ""]
    for name, i in task_ids.items():
        lines.append(f"#define MUSTER_TASK_ID_{name.upper()} {i}u")
    lines.append(f"#define MUSTER_TASK_COUNT {len(task_ids)}u")
    (out / "include" / "muster_plan.h").write_text("\n".join(lines) + "\n")

    # ---- src/muster_registry_gen.cpp : only resident tasks are referenced --
    reg = ["/* GENERATED by muster - do not edit. */",
           '#include "muster_plan.h"', "",
           "extern \"C\" void muster_register_task(unsigned id, void (*fn)(void));", ""]
    for t in analysis["tasks"]:
        reg.append(f"{t['return_type']} {t['name']}({t['params']});")
    reg += ["", "void muster_register_resident(void) {"]
    for t in analysis["tasks"]:
        i = task_ids[t["name"]]
        reg += [f"#if (MUSTER_RESIDENT_MASK & (1ul << {i}))",
                f"    muster_register_task({i}u, (void (*)(void)) &{t['name']});",
                "#endif"]
    reg.append("}")
    (out / "src" / "muster_registry_gen.cpp").write_text("\n".join(reg) + "\n")

    # ---- platformio.ini ----------------------------------------------------
    ini = ["; GENERATED by muster - do not edit by hand. Re-run `muster plan`.", "",
           "[env]",
           "build_flags =",
           "    -ffunction-sections -fdata-sections",
           "    -Wl,--gc-sections",
           "    -include muster_annotations.h", ""]
    for node_id, b in enumerate(inventory):
        p = b["spec"]["pio"]
        flags = [f"-DMUSTER_NODE_ID={node_id}",
                 f"-DMUSTER_RESIDENT_MASK={resident[b['id']]:#x}ul"]
        if b["id"] == plan["lead"]:
            flags.append("-DMUSTER_LEAD=1")
        ini += [f"[env:{_env_name(b)}]",
                f"platform = {p['platform']}",
                f"board = {p['board']}",
                f"framework = {p['framework']}",
                "build_flags =",
                "    ${env.build_flags}"] + [f"    {f}" for f in flags]
        if b.get("port"):
            ini += [f"upload_port = {b['port']}", f"monitor_port = {b['port']}"]
        ini.append("")
    (out / "platformio.ini").write_text("\n".join(ini))
    return out / "platformio.ini", resident


def deploy(inventory, project_dir, dry_run=False):
    """Build and upload every board, lead last so workers are listening first."""
    lead_last = sorted(inventory, key=lambda b: b.get("is_lead", False))
    cmds = [["pio", "run", "-d", str(project_dir), "-e", _env_name(b), "-t", "upload"]
            for b in lead_last]
    for c in cmds:
        print("  $ " + " ".join(c))
        if not dry_run:
            r = subprocess.run(c)
            if r.returncode != 0:
                raise SystemExit(f"upload failed for {c[5]}; stopping so the bus is not "
                                 f"left half-flashed.")
    return cmds
